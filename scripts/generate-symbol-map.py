#!/usr/bin/env python3
"""
Generate the symbol-font re-encoding tables in
crates/parasma-wasm/src/wml/symbol_font.rs.

Symbol, Wingdings, Wingdings 2, Wingdings 3 and Webdings are fonts whose
character codes do not mean what Unicode says they mean: in Wingdings, "ü"
(0xFC) draws a check mark. A viewer without those fonts has to re-encode each
code to the Unicode character the font actually draws, and then pick a face that
has that character. This script builds both halves:

  1. The code -> Unicode mapping, from the Unicode Consortium's own sources:
       - Symbol: the Adobe Symbol mapping table
         (https://www.unicode.org/Public/MAPPINGS/VENDORS/ADOBE/symbol.txt)
       - Wingdings, Wingdings 2, Wingdings 3, Webdings: the UTC document
         L2/12-368 (WG2 N4384), "Status of encoding of Wingdings and Webdings
         Symbols", which gives the code point each character was encoded at.
  2. The face that draws each target, chosen by reading the cmap of every
     bundled candidate face at the exact pinned URL the viewer fetches (read
     from @parasma/core, so this script cannot drift from the shipping URLs).

Usage:
    python3 scripts/generate-symbol-map.py

Needs network access, `bun` (to read the font URLs) and `pdftotext` (poppler).
"""

import json
import re
import struct
import subprocess
import sys
import tempfile
import unicodedata
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "crates/parasma-wasm/src/wml/symbol_font.rs"
CORE_PKG = ROOT / "packages/parasma-core"

SYMBOL_URL = "https://www.unicode.org/Public/MAPPINGS/VENDORS/ADOBE/symbol.txt"
L2_URL = "https://www.unicode.org/L2/L2012/12368-n4384.pdf"

BEGIN = "// BEGIN GENERATED by scripts/generate-symbol-map.py — do not edit by hand."
END = "// END GENERATED"

# The faces a re-encoded character can draw in, by engine variant name and the
# FONT_URLS key the engine requests. `Base` is the run's own text face.
FACES = {
    "Tinos": "Tinos",
    "XitsMath": "XITS Math",
    "DejaVuSans": "DejaVuSans",
    "NotoSymbols2": "Noto Sans Symbols 2",
}
# The text faces a run's base family most often resolves to. A non-letter
# target all of them carry stays in the run's own face: no fetch, and the
# glyph matches the surrounding text.
BASE_FACES = ["Carlito", "Arimo", "Tinos"]

# Preference order after `Base`. Symbol is a Times-style face, so its Greek and
# operators prefer the Times-metric Tinos, then the STIX-derived XITS Math.
SYMBOL_ORDER = ["Tinos", "XitsMath", "DejaVuSans", "NotoSymbols2"]
DINGBAT_ORDER = ["NotoSymbols2", "DejaVuSans", "XitsMath", "Tinos"]

# L2/12-368 numbers each character w-SCCC: set S (0 Webdings, 1 Wingdings,
# 2 Wingdings 2, 3 Wingdings 3) and decimal character code CCC.
L2_SETS = {0: "WEBDINGS", 1: "WINGDINGS", 2: "WINGDINGS_2", 3: "WINGDINGS_3"}
EXPECTED_COUNTS = {"WEBDINGS": 222, "WINGDINGS": 221, "WINGDINGS_2": 216, "WINGDINGS_3": 207}
# Known pairs the parse must reproduce — the bullets and check boxes that
# documents use most.
SPOT_CHECKS = {
    ("WINGDINGS", 0x9F): 0x2022, ("WINGDINGS", 0xA7): 0x25AA,
    ("WINGDINGS", 0xD8): 0x2B9A, ("WINGDINGS", 0xFC): 0x2713,
    ("WINGDINGS", 0xFE): 0x1F5F9, ("WINGDINGS", 0x76): 0x2756,
    ("WINGDINGS", 0x71): 0x2751, ("WINGDINGS", 0x6C): 0x26AB,
    ("WINGDINGS_2", 0x50): 0x1F5F8, ("WEBDINGS", 0x21): 0x1F577,
    ("WINGDINGS_3", 0x21): 0x2B60,
}


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "parasma-generator"})
    with urllib.request.urlopen(req) as r:
        return r.read()


def cmap(data: bytes) -> set:
    """Every code point a font's cmap (formats 4 and 12) maps."""
    n = struct.unpack(">H", data[4:6])[0]
    tables = {}
    for i in range(n):
        tag, _, off, _ = struct.unpack(">4sIII", data[12 + 16 * i:28 + 16 * i])
        tables[tag] = off
    off = tables[b"cmap"]
    cps = set()
    for i in range(struct.unpack(">H", data[off + 2:off + 4])[0]):
        _, _, so = struct.unpack(">HHI", data[off + 4 + 8 * i:off + 12 + 8 * i])
        s = off + so
        fmt = struct.unpack(">H", data[s:s + 2])[0]
        if fmt == 12:
            for g in range(struct.unpack(">I", data[s + 12:s + 16])[0]):
                a, b, _ = struct.unpack(">III", data[s + 16 + 12 * g:s + 28 + 12 * g])
                cps.update(range(a, b + 1))
        elif fmt == 4:
            seg = struct.unpack(">H", data[s + 6:s + 8])[0] // 2
            ends = struct.unpack(">%dH" % seg, data[s + 14:s + 14 + 2 * seg])
            starts = struct.unpack(">%dH" % seg, data[s + 16 + 2 * seg:s + 16 + 4 * seg])
            for a, b in zip(starts, ends):
                if a != 0xFFFF:
                    cps.update(range(a, b + 1))
    return cps


def is_pua(cp: int) -> bool:
    return 0xE000 <= cp <= 0xF8FF


def parse_symbol(text: str) -> dict:
    """Adobe Symbol code -> Unicode. Five codes list two values; the Greek
    letter wins (Symbol is a Greek face: 0x6D is mu, not MICRO SIGN), otherwise
    the first listed. Corporate-use (PUA) values are not Unicode characters."""
    out = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        uni, code = line.split("\t")[:2]
        cp, code = int(uni, 16), int(code, 16)
        if is_pua(cp):
            continue
        prev = out.get(code)
        if prev is None or (0x0370 <= cp <= 0x03FF and not 0x0370 <= prev <= 0x03FF):
            out[code] = cp
    return out


def parse_l2(text: str) -> dict:
    """The four dingbat tables from the layout text of L2/12-368.

    Each record is a 4-digit ID at the start of a line and a UCS code point in
    the column beside it, sometimes a line above or below. Code points in the
    comment column (cross-references, "→ 1F4CE") are not the record's own."""
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if i > 1000 and l.strip() == "Webdings")
    id_re = re.compile(r"^([0-3])(0[3-9]\d|1\d\d|2[0-5]\d)\b")
    hex_re = re.compile(r"(?<![\w→])([0-9A-F]{4,5})(?!\w)")
    ids, ucs = [], []
    for ln in range(start, len(lines)):
        line = lines[ln]
        m = id_re.match(line)
        if m:
            ids.append((ln, int(m.group(1)), int(m.group(2))))
        offset = m.end() if m else 0
        rest = line[offset:]
        for h in hex_re.finditer(rest):
            if h.start() + offset > 34 or "→" in rest[:h.start()]:
                continue
            ucs.append((ln, int(h.group(1), 16)))
    used, out = set(), {name: {} for name in L2_SETS.values()}
    for ln, s, code in ids:
        best = None
        for j, (uln, _) in enumerate(ucs):
            d = uln - ln
            if j in used or abs(d) > 4:
                continue
            key = (abs(d), d < 0)
            if best is None or key < best[0]:
                best = (key, j)
        if best is None:
            continue  # w-1255, the Windows logo: deliberately not encoded
        used.add(best[1])
        out[L2_SETS[s]][code] = ucs[best[1]][1]
    for name, n in EXPECTED_COUNTS.items():
        if len(out[name]) != n:
            sys.exit(f"L2/12-368 parse drifted: {name} has {len(out[name])} entries, expected {n}")
    for (name, code), cp in SPOT_CHECKS.items():
        if out[name].get(code) != cp:
            sys.exit(f"L2/12-368 parse drifted: {name} 0x{code:02X} -> {out[name].get(code)}, expected U+{cp:04X}")
    return out


def choose_face(cp: int, order: list, faces: dict, base: set) -> str:
    if cp in base and not unicodedata.category(chr(cp)).startswith("L"):
        return "Base"
    # No bundled face has it: draw in the run's face and let the browser's own
    # fallback find a glyph. Listed in the generated header.
    return next((f for f in order if cp in faces[f]), "Base")


def main():
    out = subprocess.run(
        ["bun", "-e", 'import { BUNDLED_FONT_FAMILIES } from "./src/font-resolver";'
         " console.log(JSON.stringify(BUNDLED_FONT_FAMILIES))"],
        cwd=CORE_PKG, capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit("could not read font URLs from @parasma/core:\n" + out.stderr.strip())
    urls = json.loads(out.stdout)
    faces = {v: cmap(fetch(urls[key]["regular"])) for v, key in FACES.items()}
    base_sets = [cmap(fetch(urls[f]["regular"])) for f in BASE_FACES]
    base = set.intersection(*base_sets)

    with tempfile.TemporaryDirectory() as tmp:
        pdf = Path(tmp) / "l2.pdf"
        pdf.write_bytes(fetch(L2_URL))
        txt = Path(tmp) / "l2.txt"
        subprocess.run(["pdftotext", "-layout", str(pdf), str(txt)], check=True)
        tables = parse_l2(txt.read_text())
    tables["SYMBOL"] = parse_symbol(fetch(SYMBOL_URL).decode("latin-1"))
    for t in tables.values():
        t.setdefault(0x20, 0x20)

    body = [BEGIN, "//", "// Code -> (Unicode, face) for the five symbol fonts. Sources: the Unicode",
            "// Consortium's Adobe Symbol mapping and UTC document L2/12-368; faces chosen",
            "// from the cmaps of the pinned bundled fonts. Codes no bundled face covers",
            "// stay `Base` and draw through the browser's own font fallback:"]
    uncovered = []
    sections = []
    for name in ["SYMBOL", "WINGDINGS", "WINGDINGS_2", "WINGDINGS_3", "WEBDINGS"]:
        order = SYMBOL_ORDER if name == "SYMBOL" else DINGBAT_ORDER
        rows = []
        for code, cp in sorted(tables[name].items()):
            face = choose_face(cp, order, faces, base)
            if face == "Base" and cp not in base:
                uncovered.append(f"{name} 0x{code:02X} U+{cp:04X}")
            rows.append(f"    (0x{code:02X}, '\\u{{{cp:04X}}}', {face}),")
        sections += [f"pub(super) static {name}: &[(u8, char, SymbolFace)] = &[", *rows, "];"]
    for i in range(0, len(uncovered), 3):
        body.append("//   " + ", ".join(uncovered[i:i + 3]))
    body += ["mod table {", "    use super::SymbolFace::{self, *};", ""]
    body += ["    " + l if l else l for l in sections]
    body += ["}", END]

    src = OUTPUT.read_text()
    head, rest = src.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    OUTPUT.write_text(head + "\n".join(body) + tail)
    print(f"wrote {OUTPUT.relative_to(ROOT)}: "
          + ", ".join(f"{k} {len(v)}" for k, v in tables.items())
          + f"; {len(uncovered)} uncovered")


if __name__ == "__main__":
    main()
