//! Text set in a symbol font — Symbol, Wingdings, Wingdings 2, Wingdings 3 and
//! Webdings — re-encoded to the Unicode characters those fonts draw.
//!
//! These fonts give character codes their own meaning: in Wingdings "ü" (0xFC)
//! draws a check mark and "§" (0xA7) a small square bullet. A document carries
//! such text either as ordinary characters in a run whose font is the symbol
//! font (§17.3.2.26 `rFonts`), or as a `w:sym` element naming the font and a hex
//! code (§17.3.3.30), conventionally the code's private-use alias
//! U+F020–U+F0FF. None of these fonts ships with the viewer, so without
//! re-encoding the check mark draws as "ü" in the body face.
//!
//! Each code maps to the character the font draws and to the bundled face that
//! draws it ([`SymbolFace`]). The tables at the end of this file are generated
//! by `scripts/generate-symbol-map.py` from the Unicode Consortium's mappings.
//!
//! Deviation, declared: a re-encoded character draws in a substitute face but
//! keeps its run's base face for the line box (`RunStyle::line_metrics_family`).
//! The substitute faces' ascent and descent are not the symbol fonts' — Noto
//! Sans Symbols 2 is 1.7 em tall — and would grow every line that holds one.
//!
//! Text is re-encoded even when the symbol font itself is installed locally:
//! the bundled faces draw every character, and one rule serves runs and list
//! markers alike.

use crate::engine::fonts::MATH_FAMILY;

/// The family the dingbat fallback face is fetched and registered under.
pub(crate) const SYMBOLS_FAMILY: &str = "Noto Sans Symbols 2";

/// One of the five symbol fonts this module re-encodes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum SymbolFont { Symbol, Wingdings, Wingdings2, Wingdings3, Webdings }

/// The face a re-encoded character draws in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum SymbolFace {
    /// The run's own text face: every common text substitute carries the
    /// character, so no fetch is needed. Also the fallback for the few
    /// characters no bundled face covers (listed in the generated header).
    Base,
    Tinos,
    XitsMath,
    DejaVuSans,
    NotoSymbols2,
}

impl SymbolFace {
    /// The bundled family this face is fetched and registered under — a
    /// `FONT_URLS` key in `@parasma/core` — or `None` for the run's own face.
    pub(crate) fn family(self) -> Option<&'static str> {
        match self {
            SymbolFace::Base => None,
            SymbolFace::Tinos => Some("Tinos"),
            SymbolFace::XitsMath => Some(MATH_FAMILY),
            SymbolFace::DejaVuSans => Some("DejaVuSans"),
            SymbolFace::NotoSymbols2 => Some(SYMBOLS_FAMILY),
        }
    }
}

impl SymbolFont {
    /// The symbol font `family` names, if it names one. Matching ignores case,
    /// spaces and hyphens, and reads the first name of a `;`-separated list.
    pub(crate) fn from_family(family: &str) -> Option<Self> {
        let first = family.split(';').next().unwrap_or("");
        let key: String = first
            .chars()
            .filter(|c| !matches!(c, ' ' | '-'))
            .flat_map(char::to_lowercase)
            .collect();
        match key.as_str() {
            "symbol" => Some(SymbolFont::Symbol),
            "wingdings" => Some(SymbolFont::Wingdings),
            "wingdings2" => Some(SymbolFont::Wingdings2),
            "wingdings3" => Some(SymbolFont::Wingdings3),
            "webdings" => Some(SymbolFont::Webdings),
            _ => None,
        }
    }

    fn table(self) -> &'static [(u8, char, SymbolFace)] {
        match self {
            SymbolFont::Symbol => table::SYMBOL,
            SymbolFont::Wingdings => table::WINGDINGS,
            SymbolFont::Wingdings2 => table::WINGDINGS_2,
            SymbolFont::Wingdings3 => table::WINGDINGS_3,
            SymbolFont::Webdings => table::WEBDINGS,
        }
    }

    /// Re-encode one character: the font's code is the character itself
    /// (U+0020–U+00FF) or its private-use alias (U+F020–U+F0FF). `None` when
    /// the font draws nothing at that code.
    pub(crate) fn map(self, c: char) -> Option<(char, SymbolFace)> {
        let cp = c as u32;
        let code = if (0xF020..=0xF0FF).contains(&cp) { cp - 0xF000 } else { cp };
        let code = u8::try_from(code).ok().filter(|&b| b >= 0x20)?;
        let table = self.table();
        let i = table.binary_search_by_key(&code, |e| e.0).ok()?;
        Some((table[i].1, table[i].2))
    }

    /// Re-encode a whole string that draws as one item (a list marker), and
    /// the face it draws in: the first face other than `Base` any of its
    /// characters needs. Characters the font draws nothing for pass through.
    pub(crate) fn reencode(self, text: &str) -> (String, SymbolFace) {
        let mut face = SymbolFace::Base;
        let text = text
            .chars()
            .map(|c| match self.map(c) {
                Some((u, f)) => {
                    if face == SymbolFace::Base {
                        face = f;
                    }
                    u
                }
                None => c,
            })
            .collect();
        (text, face)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_match_loosely() {
        assert_eq!(SymbolFont::from_family("Wingdings"), Some(SymbolFont::Wingdings));
        assert_eq!(SymbolFont::from_family("wingdings 2"), Some(SymbolFont::Wingdings2));
        assert_eq!(SymbolFont::from_family("Wingdings-3"), Some(SymbolFont::Wingdings3));
        assert_eq!(SymbolFont::from_family("Symbol;Arial"), Some(SymbolFont::Symbol));
        assert_eq!(SymbolFont::from_family("Segoe UI Symbol"), None);
        assert_eq!(SymbolFont::from_family("Arial"), None);
    }

    #[test]
    fn raw_codes_and_private_use_aliases_map_alike() {
        let w = SymbolFont::Wingdings;
        assert_eq!(w.map('\u{FC}'), Some(('\u{2713}', SymbolFace::NotoSymbols2)), "ü is a check mark");
        assert_eq!(w.map('\u{F0FC}'), w.map('\u{FC}'));
        assert_eq!(w.map('\u{A7}').map(|m| m.0), Some('\u{25AA}'), "§ is the square bullet");
        assert_eq!(w.map('\u{F0D8}').map(|m| m.0), Some('\u{2B9A}'));
        assert_eq!(w.map('\u{2713}'), None, "a code above 0xFF is no Wingdings code");
        assert_eq!(w.map('\u{1F}'), None);
    }

    #[test]
    fn symbol_keeps_common_characters_in_the_run_face() {
        let s = SymbolFont::Symbol;
        assert_eq!(s.map('\u{F0B7}'), Some(('\u{2022}', SymbolFace::Base)), "the bullet needs no fetch");
        assert_eq!(s.map('a'), Some(('\u{3B1}', SymbolFace::Tinos)), "Greek draws in the Times-style face");
        assert_eq!(s.map('m').map(|m| m.0), Some('\u{3BC}'), "mu, not MICRO SIGN");
    }

    #[test]
    fn a_marker_draws_in_the_face_its_characters_need() {
        assert_eq!(SymbolFont::Wingdings.reencode("\u{F0FC}"), ("\u{2713}".into(), SymbolFace::NotoSymbols2));
        assert_eq!(SymbolFont::Wingdings.reencode("\u{A7}\u{FC}").1, SymbolFace::NotoSymbols2, "the first face a fetch needs");
        assert_eq!(SymbolFont::Symbol.reencode("\u{F0B7}"), ("\u{2022}".into(), SymbolFace::Base));
        assert_eq!(SymbolFont::Wingdings.reencode("\u{2022}"), ("\u{2022}".into(), SymbolFace::Base), "not a code: kept");
    }

    #[test]
    fn every_table_is_sorted_and_names_a_real_character() {
        for font in [SymbolFont::Symbol, SymbolFont::Wingdings, SymbolFont::Wingdings2,
                     SymbolFont::Wingdings3, SymbolFont::Webdings] {
            let t = font.table();
            assert!(t.windows(2).all(|w| w[0].0 < w[1].0), "{font:?} must be sorted for binary search");
            assert!(t.iter().all(|e| !('\u{E000}'..='\u{F8FF}').contains(&e.1)), "{font:?} maps into private use");
            assert_eq!(font.map(' ').map(|m| m.0), Some(' '));
        }
    }
}

